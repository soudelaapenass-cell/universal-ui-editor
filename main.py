"""Backend de metabusca LZN. Requer uma instância SearXNG própria/configurada."""
import os, re
from urllib.parse import urlparse
import httpx
from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware

app = FastAPI(title="LZN Search API", version="1.0")
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["GET"], allow_headers=["*"])
SEARXNG_URL = os.getenv("SEARXNG_URL", "http://127.0.0.1:8080").rstrip("/")

REGION_MAP = {
 "BR":"pt-BR","US":"en-US","CA":"en-CA","MX":"es-MX","AR":"es-AR","CL":"es-CL","CO":"es-CO","PE":"es-PE","UY":"es-UY",
 "GB":"en-GB","IE":"en-IE","FR":"fr-FR","DE":"de-DE","ES":"es-ES","PT":"pt-PT","IT":"it-IT","NL":"nl-NL","BE":"fr-BE","CH":"de-CH","AT":"de-AT",
 "SE":"sv-SE","NO":"no-NO","DK":"da-DK","FI":"fi-FI","PL":"pl-PL","CZ":"cs-CZ","UA":"uk-UA","TR":"tr-TR","RU":"ru-RU","CN":"zh-CN","JP":"ja-JP","KR":"ko-KR","IN":"en-IN","PK":"en-PK","BD":"bn-BD","ID":"id-ID","MY":"ms-MY","SG":"en-SG","TH":"th-TH","VN":"vi-VN","PH":"en-PH","AU":"en-AU","NZ":"en-NZ","ZA":"en-ZA","NG":"en-NG","KE":"en-KE","EG":"ar-EG","SA":"ar-SA","AE":"ar-AE","IL":"he-IL","GR":"el-GR","RO":"ro-RO","HU":"hu-HU","HR":"hr-HR","BG":"bg-BG","IS":"is-IS","MA":"ar-MA","GH":"en-GH","ET":"am-ET","TW":"zh-TW"}
CATEGORIES = {"general":"general", "images":"images", "videos":"videos", "news":"news", "science":"science", "files":"files"}
AI_HINTS = re.compile(r"\b(ai generated|generated by ai|midjourney|stable diffusion|dall.?e|made with ai|ai-generated|artificial intelligence generated)\b", re.I)
COLOR_WORDS = {"Vermelho":"red", "Laranja":"orange", "Amarelo":"yellow", "Verde":"green", "Azul":"blue", "Roxo":"purple", "Rosa":"pink", "Preto":"black", "Branco":"white", "Cinza":"gray", "Marrom":"brown"}

@app.get("/health")
def health():
    return {"status":"ok", "service":"LZN Search API", "searxng":SEARXNG_URL}

@app.get("/api/search")
async def search(q: str = Query(min_length=1, max_length=300), category: str = "general", color: str = "", adult: str = "strict", ai: str = "all", region: str = ""):
    category = CATEGORIES.get(category, "general")
    # Keep safe search on strict or standard; explicit/adult-only searching is intentionally unsupported.
    safesearch = 2 if adult == "strict" else 1 if adult == "moderate" else 2
    query = q.strip()
    if color in COLOR_WORDS:
        query += " " + COLOR_WORDS[color]
    params = {"q": query, "format":"json", "categories":category, "safesearch":safesearch}
    if region in REGION_MAP:
        params["language"] = REGION_MAP[region]
    try:
        async with httpx.AsyncClient(timeout=18, follow_redirects=True) as client:
            response = await client.get(SEARXNG_URL + "/search", params=params, headers={"User-Agent":"LZNBrowser/1.0"})
            response.raise_for_status()
            data = response.json()
    except Exception as exc:
        raise HTTPException(status_code=502, detail="Não foi possível consultar o SearXNG. Confira SEARXNG_URL e o formato JSON.") from exc
    results=[]
    for item in data.get("results", []):
        title = item.get("title") or ""
        content = item.get("content") or ""
        text = title + " " + content + " " + str(item.get("url", ""))
        ai_match = bool(AI_HINTS.search(text))
        if ai == "exclude" and ai_match: continue
        if ai == "only" and not ai_match: continue
        results.append({"title":title, "url":item.get("url", ""), "pretty_url":item.get("pretty_url") or item.get("url", ""), "content":content, "engine":item.get("engine", "")})
        if len(results) >= 50: break
    return {"query":q, "category":category, "region":region or "any", "results":results, "note":"Filtro de IA é heurístico e pode errar; cor é acrescentada à consulta. O backend é um metabuscador, não um índice independente da web."}
